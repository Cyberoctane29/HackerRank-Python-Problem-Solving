# Problem: Loops
# Difficulty: Easy
# Skills: Python (Basic)

# Problem Statement:
# Given a non-negative integer n, print the square of every
# non-negative integer i such that i < n.
# Print each square on a separate line.

# Sample Input:
# 5

# Sample Output:
# 0
# 1
# 4
# 9
# 16

# Explanation:
# The integers less than 5 are 0, 1, 2, 3, and 4.
# Their squares are 0, 1, 4, 9, and 16, respectively.

# Solution:
n = int(input())

for i in range(n):
    print(i ** 2)

# Intuition:
# - Use a for loop to iterate through all integers from 0 to n - 1.
# - Square each integer using the exponentiation operator (**)
#   and print the result.

# Explanation:
# - int(input()) reads the input and converts it to an integer.
# - range(n) generates integers from 0 up to, but not including, n.
# - The loop variable i takes each integer generated by range(n).
# - i ** 2 calculates the square of the current integer.
# - print(i ** 2) outputs each square on a separate line.